    @staticmethod
    def solve_equilibrium(initial_state: Array, obj: "TPJBSolver"):
        state = initial_state.copy()
        pad_total = obj.pad_count
        Rb = obj.bearing.Rb
        Cb = obj.bearing.Cb
        Cp = obj.bearing.Cp
        fdZ = obj.bearing.fdZ
        ep_jp = obj.bearing.ep_jp
        ep_jv = obj.bearing.ep_jv
        sig = obj.asperity.sig
        pad_force = np.zeros((2, pad_total))
        err = 1.0
        tol = 1e-6
        iter_count = 0
        max_iter = 60
        JacF = np.zeros((2, 2))

        while err > tol and iter_count < max_iter:
            for pad_index in range(pad_total):
                idx = TPJBSolver.pad_idx(pad_index + 1, pad_total)
                _pad_moment, pad_force_vec, P_, p_lub_, p_cont_, *_ = TPJBSolver.solveP_simplified(
                    state[idx - 1],
                    obj.pressure_state.thetaTa[pad_index],
                    obj.matTh_flat[:, pad_index],
                    obj.matZ_flat[:, pad_index],
                    obj.matP_flat[:, pad_index],
                    obj.matC_flat[:, pad_index],
                    obj.matT_flat[:, pad_index],
                    obj.vecR[pad_index],
                    obj.vecThAvg[pad_index],
                    obj.matTh_fine[:, :, pad_index],
                    obj.vecR_fine[pad_index],
                    obj.vecThAvg_fine[pad_index],
                    obj,
                )
                pad_force[:, pad_index] = pad_force_vec
                obj.matP_flat[:, pad_index] = P_.ravel(order="F")
                obj.p_lub[:, :, pad_index] = p_lub_
                obj.p_cont[:, :, pad_index] = p_cont_

            F0 = pad_force.sum(axis=1)
            err = np.linalg.norm(F0 + obj.ref_state.Fex) / max(1.0, np.linalg.norm(obj.ref_state.Fex))
            if err <= tol:
                hmin = np.full(pad_total, np.inf)
                for pad_index in range(pad_total):
                    idx = TPJBSolver.pad_idx(pad_index + 1, pad_total)
                    dep = np.zeros(2)
                    h_vals = TPJBSolver.film_thickness_vec(
                        state[idx - 1] + np.concatenate((dep, np.zeros(6))),
                        Rb,
                        Cb,
                        Cp,
                        obj.bearing.Mp,
                        obj.pressure_state.thetaTa[pad_index],
                        obj.vecThLine[pad_index],
                    )
                    hmin[pad_index] = h_vals.min()
                lambda_val = hmin.min() / sig
                matP = obj.matP_flat * (obj.ref_state.pRef - obj.ref_state.pCav) + obj.ref_state.pCav
                out = {"iter": iter_count, "err": err}
                return state, matP, -JacF, np.zeros((2, 2)), lambda_val, out

            Fjpp = np.zeros((2 + 2 * pad_total, 2))
            Fjpm = np.zeros_like(Fjpp)
            for i in range(2):
                Fjpp[:, i] = TPJBSolver.getF(state + ep_jp * fdZ(i + 1), obj)
                Fjpm[:, i] = TPJBSolver.getF(state - ep_jp * fdZ(i + 1), obj)
            JacF = (Fjpp[:2, :2] - Fjpm[:2, :2]) / (2 * ep_jp)
            dep = -np.linalg.solve(JacF, F0 + obj.ref_state.Fex)

            a = 1.0
            for pad_index in range(pad_total):
                good = False
                idx = TPJBSolver.pad_idx(pad_index + 1, pad_total)
                while not good:
                    hmin = TPJBSolver.film_thickness_vec(
                        state[idx - 1] + np.concatenate((a * dep, np.zeros(6))),
                        Rb,
                        Cb,
                        Cp,
                        obj.bearing.Mp,
                        obj.pressure_state.thetaTa[pad_index],
                        obj.vecThLine[pad_index],
                    ).min()
                    if hmin <= 0.5 * sig:
                        a /= 1.5
                        if a < 1e-6:
                            break
                    else:
                        good = True
                if a < 1e-6:
                    break
            state[:2] = state[:2] + a * dep
            iter_count += 1

        matP = obj.matP_flat * (obj.ref_state.pRef - obj.ref_state.pCav) + obj.ref_state.pCav
        C = np.zeros((2, 2))
        if obj.options.Dyn:
            ep_idx = np.arange(2) + (2 + 2 * pad_total)
            Fjvp = np.zeros((2 + 2 * pad_total, 2))
            Fjvm = np.zeros_like(Fjvp)
            for i in range(2):
                j = ep_idx[i]
                Fjvp[:, i] = TPJBSolver.getF(state + ep_jv * obj.bearing.fdZ(j + 1), obj)
                Fjvm[:, i] = TPJBSolver.getF(state - ep_jv * obj.bearing.fdZ(j + 1), obj)
            C = -(Fjvp[:2, :2] - Fjvm[:2, :2]) / (2 * ep_jv)

        out = {"iter": iter_count, "err": err}
        lambda_val = np.nan
        return state, matP, -JacF, C, lambda_val, out

    @staticmethod
    def getF(test_state: Array, obj: "TPJBSolver") -> Array:
        response = np.zeros(2 + 2 * obj.pad_count)
        pad_force = np.zeros((2, obj.pad_count))
        for pad_index in range(obj.pad_count):
            idx = TPJBSolver.pad_idx(pad_index + 1, obj.pad_count)
            pad_moment, pad_force_vec, *_ = TPJBSolver.solveP_simplified(
                test_state[idx - 1],
                obj.pressure_state.thetaTa[pad_index],
                obj.matTh_flat[:, pad_index],
                obj.matZ_flat[:, pad_index],
                obj.matP_flat[:, pad_index],
                obj.matC_flat[:, pad_index],
                obj.matT_flat[:, pad_index],
                obj.vecR[pad_index],
                obj.vecThAvg[pad_index],
                obj.matTh_fine[:, :, pad_index],
                obj.vecR_fine[pad_index],
                obj.vecThAvg_fine[pad_index],
                obj,
            )
            pad_force[:, pad_index] = pad_force_vec
            response[2 + pad_index] = pad_moment
        response[:2] = pad_force.sum(axis=1)
        return response

    @staticmethod
    def film_thickness_vec(
        Zpad: Array,
        Rb: float,
        Cb: float,
        Cp: float,
        Mp: float,
        thetaTa: float,
        matTh: Array,
    ) -> Array:
        ep = Zpad[:2]
        tl = Zpad[2]
        pv = Zpad[3]
        eca = np.arctan2(ep[1], ep[0])
        return (
            Cp
            - ep[0] * np.cos(matTh)
            - ep[1] * np.sin(matTh)
            - Cp * Mp * np.cos(matTh - thetaTa)
            - (Rb * np.sin(matTh - thetaTa)) * tl
            - pv * np.cos(matTh - eca)
        )

    @staticmethod
    def solveP_simplified(
        Z: Array,
        thetaTa: float,
        matTh: Array,
        nodeZ: Array,
        p: Array,
        c: Array,
        matT: Array,
        r: Array,
        th: Array,
        matTh_fine: Array,
        r_fine: Array,
        th_fine: Array,
        obj: "TPJBSolver",
    ):
        bearing = obj.bearing
        ref_state = obj.ref_state
        options = obj.options
        lubricant = obj.lubricant
        Nx = obj.nx
        Nz = obj.nz
        nNode = Nx * Nz
        Rb = bearing.Rb
        Lb = bearing.Lb
        Cb = bearing.Cb
        Cp = bearing.Cp
        Mp = bearing.Mp
        aPad = bearing.aPad
        shN = obj.ref_state.shN
        shB = obj.ref_state.shB
        NCP = obj.pressure_state.NCP
        pRef = ref_state.pRef
        pCav = ref_state.pCav
        pAmb = ref_state.pAmb
        iNP = obj.pressure_state.iNP
        P0 = (pAmb - pCav) / (pRef - pCav)
        f_fp = obj.asperity.f_fp
        f_fs = obj.asperity.f_fs
        f_ff_p = obj.asperity.f_ff_p
        f_ff_s = obj.asperity.f_ff_s
        f_ff = obj.asperity.f_ff
        f_ht = obj.asperity.f_ht
        sig = obj.asperity.sig
        f_p_cont = obj.asperity.f_p_cont

        jpx, jpy, padtilt, pvdisp, jvx, jvy, tvel, pvel = Z

        node_h = (
            Cp
            - jpx * np.cos(matTh)
            - jpy * np.sin(matTh)
            - Cp * Mp * np.cos(matTh - thetaTa)
            - padtilt * (Rb * np.sin(matTh - thetaTa))
            - pvdisp * np.cos(matTh - np.arctan2(jpy, jpx))
        )

        node_dhdt = (
            -jvx * np.cos(matTh)
            - jvy * np.sin(matTh)
            - tvel * (Rb * np.sin(matTh - thetaTa))
            - pvel * np.cos(matTh - np.arctan2(jpy, jpx))
        )

        nEle = (Nx - 1) * (Nz - 1)
        hh = node_h[NCP].mean(axis=1)
        dhh = node_dhdt[NCP].mean(axis=1)
        cX_ = Rb * matTh[NCP]
        cZ_ = nodeZ[NCP]

        H = hh / sig
        fp = f_fp(H)
        fs = f_fs(H)
        ff_p = f_ff_p(H)
        ff_s = f_ff_s(H)
        ht = f_ht(H / 3, sig)
        ff = f_ff(H / 3)

        CXZ = np.stack((cZ_, cX_), axis=2)
        CXZ = CXZ.transpose(1, 2, 0)

        B1 = shB[0:2, :]
        B2 = shB[2:4, :]
        B3 = shB[4:6, :]
        B4 = shB[6:8, :]

        def pagemul(Bk: Array) -> Array:
            return np.einsum('ab,bcn->acn', Bk, CXZ)

        Js1 = pagemul(B1)
        Js2 = pagemul(B2)
        Js3 = pagemul(B3)
        Js4 = pagemul(B4)

        def pagels(Js: Array, Bk: Array) -> Array:
            rhs = np.broadcast_to(Bk, (nEle, *Bk.shape)).copy()
            solved = np.linalg.solve(Js.transpose(2, 0, 1), rhs)
            return solved.transpose(1, 2, 0)

        Bs1 = pagels(Js1, B1)
        Bs2 = pagels(Js2, B2)
        Bs3 = pagels(Js3, B3)
        Bs4 = pagels(Js4, B4)

        detJ = Js1[0, 0, :] * Js1[1, 1, :] - Js1[0, 1, :] * Js1[1, 0, :]
        SumBtB = sum(
            np.einsum('eik, ejk -> eij', Bs.transpose(2, 0, 1), Bs.transpose(2, 0, 1))
            for Bs in (Bs1, Bs2, Bs3, Bs4)
        ).transpose(1, 2, 0)

        coefA = (hh ** 3) / (12 * lubricant.mu0) * detJ
        Ae_all = SumBtB * coefA

        Bs_sum = Bs1 + Bs2 + Bs3 + Bs4
        Wu = np.array([bearing.w, bearing.u])
        term1 = np.einsum('ijn,i->jn', Bs_sum, Wu).reshape(4, 1, nEle)
        Ns_sum = shN.sum(axis=0)
        term2 = np.broadcast_to(Ns_sum[:, None, None], (4, 1, nEle))

        Ce_all = (ht / 2 + sig * fs) * term1.transpose(2, 0, 1) - dhh * term2.transpose(2, 0, 1)
        Ce_all = (Ce_all.transpose(1, 2, 0) * detJ).transpose(0, 2, 1)
        Ce_all = Ce_all / (pRef - pCav)

        nNode = NCP.max() + 1
        A = np.zeros((nNode, nNode))
        np.add.at(
            A,
            (NCP[:, :, None], NCP[:, None, :]),
            Ae_all.transpose(2, 0, 1),
        )

        Cvec = np.zeros(nNode)
        np.add.at(Cvec, NCP, Ce_all[:, 0, :].T)

        p_tmp = p.copy()
        p_tmp[iNP] = 0.0
        Cvec -= A @ p_tmp
        A_comp = A[np.ix_(iNP, iNP)]
        F_ = np.linalg.solve(np.tril(A_comp), Cvec[iNP])
        KU = np.triu(A_comp)
        nNP = iNP.sum()
        P_ = np.zeros(nNP)
        P_[-1] = max(F_[-1] / KU[-1, -1], P0)
        for n in range(nNP - 2, -1, -1):
            rhs = -KU[n, n + 1 : nNP] @ P_[n + 1 : nNP] + F_[n]
            P_[n] = max(rhs / KU[n, n], P0)

        p_new = p.copy()
        p_new[iNP] = P_

        matP = p_new.reshape(Nz, Nx, order="F")
        matp = matP * (pRef - pCav) + pCav
        meanp = 0.25 * (
            matp[:-1, :-1]
            + matp[:-1, 1:]
            + matp[1:, :-1]
            + matp[1:, 1:]
        )
        M_lub = np.sum(meanp - pAmb, axis=(0, 1)) * r.mean() * Rb * aPad * np.pi / 180 / (Nx - 1) * Lb / (Nz - 1)
        h_fine = (
            Cp
            - jpx * np.cos(matTh_fine)
            - jpy * np.sin(matTh_fine)
            - Cp * Mp * np.cos(matTh_fine - thetaTa)
            - padtilt * (Rb * np.sin(matTh_fine - thetaTa))
            - pvdisp * np.cos(matTh_fine - np.arctan2(jpy, jpx))
        )
        p_cont_fine = f_p_cont(h_fine / sig)
        Nx_fine = matTh_fine.shape[1]
        mean_p_cont_fine = 0.25 * (
            p_cont_fine[:-1, :-1]
            + p_cont_fine[:-1, 1:]
            + p_cont_fine[1:, :-1]
            + p_cont_fine[1:, 1:]
        )
        F_lub = -np.sum(meanp - pAmb) * Rb * aPad * np.pi / 180 / (Nx - 1) * Lb / (Nz - 1)
        F_cont = -np.sum(mean_p_cont_fine) * Rb * aPad * np.pi / 180 / (Nx_fine - 1) * Lb / (Nz - 1)
        F = np.array([F_lub + F_cont, F_lub + F_cont])
        M_cont_fine = np.sum(mean_p_cont_fine) * Rb * aPad * np.pi / 180 / (Nx_fine - 1) * Lb / (Nz - 1)
        M = M_lub + M_cont_fine
        p_lub = matp
        p_cont = p_cont_fine
        return M, F, matP, p_lub, p_cont, np.array([F_lub, 0.0]), np.array([F_cont, 0.0])

    @staticmethod
    def sub_2d_mesh(nRow: int, nCol: int):
        matNN = np.arange(nRow * nCol).reshape(nRow, nCol, order="F")
        nEle = (nRow - 1) * (nCol - 1)
        c1 = (np.arange(nRow - 1)[:, None] + np.arange(0, nRow * (nCol - 1), nRow)).ravel(order="F")
        c2 = c1 + 1
        c3 = c2 + nRow - 1
        c4 = c1 + nRow - 1
        matNC = np.vstack((c1, c2, c3, c4)).T
        matEleType = np.zeros((nEle, 4), dtype=int)
        matNodalNC = matNC.copy()
        return matNC, matNodalNC, matEleType, matNN

    @staticmethod
    def sub_shape_funs(nEO: int):
        if nEO != 4:
            raise NotImplementedError("Only 4-node elements are implemented in the Python port.")
        nGI = 4
        weights = np.ones(nGI)
        points = np.array([
            [-1 / np.sqrt(3), 1 / np.sqrt(3), 1 / np.sqrt(3), -1 / np.sqrt(3)],
            [-1 / np.sqrt(3), -1 / np.sqrt(3), 1 / np.sqrt(3), 1 / np.sqrt(3)],
        ])
        shN = np.zeros((nGI, 4))
        shB = np.zeros((2 * nGI, 4))
        W11 = lambda xi: np.array([(1 - xi) / 2, (1 + xi) / 2, (1 + xi) / 2, (1 - xi) / 2])
        W12 = lambda xi: np.array([
            -0.75 * (1 - xi) * (1 + xi),
            +0.75 * (1 - xi) * (1 + xi),
            +0.75 * (1 - xi) * (1 + xi),
            -0.75 * (1 - xi) * (1 + xi),
        ])
        W21 = lambda eta: np.array([(1 - eta) / 2, (1 - eta) / 2, (1 + eta) / 2, (1 + eta) / 2])
        W22 = lambda eta: np.array([
            -0.75 * (1 - eta) * (1 + eta),
            -0.75 * (1 - eta) * (1 + eta),
            +0.75 * (1 - eta) * (1 + eta),
            +0.75 * (1 - eta) * (1 + eta),
        ])
        W11_all = np.zeros((nGI, 4))
        W12_all = np.zeros((nGI, 4))
        W21_all = np.zeros((nGI, 4))
        W22_all = np.zeros((nGI, 4))
        for i in range(nGI):
            xi = points[0, i]
            eta = points[1, i]
            shN[i, :] = (
                (eta / 2 - 1 / 2) * (xi / 2 - 1 / 2),
                -(eta / 2 - 1 / 2) * (xi / 2 + 1 / 2),
                (eta / 2 + 1 / 2) * (xi / 2 + 1 / 2),
                -(eta / 2 + 1 / 2) * (xi / 2 - 1 / 2),
            )
            shB[2 * i : 2 * i + 2, :] = np.array(
                [[eta - 1, 1 - eta, eta + 1, -eta - 1], [xi - 1, -xi - 1, xi + 1, 1 - xi]]
            ) / 4
            W11_all[i, :] = W11(xi)
            W12_all[i, :] = W12(xi)
            W21_all[i, :] = W21(eta)
            W22_all[i, :] = W22(eta)

        shW = lambda upA, upB: (W11_all + upA * W12_all) * (W21_all + upB * W22_all)
        shdW = lambda upA, upB: np.zeros_like(W11_all)
        shQ = np.zeros((4, 4))
        return shN, shB, shW, shdW, shQ, weights, points, nGI
