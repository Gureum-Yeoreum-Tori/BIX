    def set_operating(self, acond: Dict[str, Any]) -> SolverOutcome:
        acond = dict(acond)
        bearing_diameter = self.bearing.Db
        bearing_length = self.bearing.Lb
        pad_clearance = self.bearing.Cp
        lubricant_viscosity = self.lubricant.mu0

        sommerfeld_target = acond.get("S")
        load = acond.get("load")
        shaft_speed = acond.get("omega")

        if sommerfeld_target is not None and load is not None:
            sommerfeld_target = float(sommerfeld_target)
            load = float(load)
            omega_iter = load * sommerfeld_target / (
                lubricant_viscosity
                * bearing_diameter
                * bearing_length
                * (bearing_diameter / 2 / pad_clearance) ** 2
            ) * (2 * np.pi)
            iteration_values = np.atleast_1d(omega_iter)
            mode = "load"
        elif sommerfeld_target is not None and shaft_speed is not None:
            sommerfeld_target = float(sommerfeld_target)
            shaft_speed = float(shaft_speed)
            load_iter = (
                lubricant_viscosity
                * shaft_speed
                / (2 * np.pi)
                * bearing_diameter
                * bearing_length
                * (bearing_diameter / 2 / pad_clearance) ** 2
                / sommerfeld_target
            )
            iteration_values = np.atleast_1d(load_iter)
            mode = "speed"
        else:
            raise ValueError("`set_operating` requires either (S & load) or (S & omega).")

        iteration_count = iteration_values.size
        equilibrium_history = np.zeros((iteration_count, self.state_vector.size))
        stiffness_history = np.zeros((iteration_count, 4))
        damping_history = np.zeros((iteration_count, 4))
        lambda_history = np.zeros(iteration_count)
        load_history = np.zeros(iteration_count)

        for idx in range(iteration_count):
            if mode == "load":
                omg = float(iteration_values[idx])
                load_val = load
            else:
                omg = shaft_speed
                load_val = float(iteration_values[idx])

            self.bearing.u = bearing_diameter / 2 * omg
            self.bearing.ep_jp = min(self.bearing.Cp / 1e3, self.asperity.sig)
            self.bearing.ep_jv = self.bearing.ep_jp * omg / 1e2
            self.bearing.ep_pt = 1e-6
            self.bearing.ep_pa = self.bearing.ep_pt * omg
            self.bearing.ep_pvd = self.bearing.ep_jp
            self.bearing.ep_pvv = self.bearing.ep_jv

            self.ref_state.Fex = load_val * np.array([np.cos(self.ref_state.thetaF), np.sin(self.ref_state.thetaF)])

            # self.bearing.ep_jv = self.bearing.ep_jp * omg / 1e2  # redundant with assignment above

            zeq, matP, K_, C_, lambda_val, out = self.solve_equilibrium(self.state_vector, self)
            equilibrium_history[idx, :] = zeq
            stiffness_history[idx, :] = K_.reshape(-1)
            damping_history[idx, :] = C_.reshape(-1)
            lambda_history[idx] = lambda_val
            load_history[idx] = load_val

            self.state_vector = zeq
            self.z_equilibrium = zeq
            self.stiffness_matrix = K_
            self.damping_matrix = C_
            self.last_error = out["err"]
            self.last_iteration = out["iter"]

        self.sommerfeld_number = sommerfeld_target if sommerfeld_target is not None else np.nan
        return SolverOutcome(
            zeq=equilibrium_history.squeeze(),
            K=stiffness_history.reshape(iteration_count, 2, 2).squeeze(),
            C=damping_history.reshape(iteration_count, 2, 2).squeeze(),
            sommerfeld=self.sommerfeld_number,
            load=float(load_history[-1]),
            lambda_min=float(lambda_history[-1]),
        )

    def force(self, displacement: Iterable[float], velocity: Iterable[float]) -> Tuple[Array, Array]:
        displacement = np.asarray(displacement, dtype=float).reshape(2)
        velocity = np.asarray(velocity, dtype=float).reshape(2)

        trial_state = self.z_equilibrium.copy()
        if trial_state.size == 0:
            trial_state = self.state_vector.copy()
        trial_state[:2] = displacement
        offset = 2 + 2 * self.pad_count
        trial_state[offset : offset + 2] = velocity
        trial_state[offset + 2 : offset + 2 + self.pad_count] = 0.0
        trial_state[offset + 2 + self.pad_count : offset + 2 + 2 * self.pad_count] = 0.0

        pad_force = np.zeros((2, self.pad_count))
        pad_moment = np.zeros(self.pad_count)
        lubrication_force_components = np.zeros((2, self.pad_count))
        contact_force_components = np.zeros((2, self.pad_count))

        for pad_index in range(self.pad_count):
            idx = self.pad_idx(pad_index + 1, self.pad_count)
            res = self.solveP_simplified(
                trial_state[idx - 1],
                self.pressure_state.thetaTa[pad_index],
                self.matTh_flat[:, pad_index],
                self.matZ_flat[:, pad_index],
                self.matP_flat[:, pad_index],
                self.matC_flat[:, pad_index],
                self.matT_flat[:, pad_index],
                self.vecR[pad_index],
                self.vecThAvg[pad_index],
                self.matTh_fine[:, :, pad_index],
                self.vecR_fine[pad_index],
                self.vecThAvg_fine[pad_index],
                self,
            )
            (
                pad_moment[pad_index],
                pad_force[:, pad_index],
                P_,
                p_lub_,
                p_cont_,
                lubrication_force_components[:, pad_index],
                contact_force_components[:, pad_index],
            ) = res
            self.matP_flat[:, pad_index] = P_.ravel(order="F")
            self.p_lub[:, :, pad_index] = p_lub_
            self.p_cont[:, :, pad_index] = p_cont_

        total_force = pad_force.sum(axis=1)
        self.force_lubrication = lubrication_force_components.sum(axis=1)
        self.force_contact = contact_force_components.sum(axis=1)
        return total_force, pad_moment

